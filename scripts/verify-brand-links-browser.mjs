import { chromium } from 'playwright';
import assert from 'node:assert/strict';
const browser = await chromium.launch({ headless: true });
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  await context.addInitScript(() => {
    if (localStorage.getItem('brand-qa-initialized')) return;
    localStorage.setItem('brand-qa-initialized', 'true');
    localStorage.setItem('memoire_demo_workspace', 'interactive-demo');
    localStorage.setItem('memoire.sampleData.loaded', 'true');
    const at = '2026-10-08T00:00:00.000Z';
    localStorage.setItem('memoire.opportunities.v1', JSON.stringify([{ id: 'sample-legacy', accountName: 'Acme', opportunityName: 'Legacy project', brand: 'Tailin', stage: 'Proposal', status: 'Active', currency: 'SGD', estimatedValue: 100, source: 'demo', isSample: true, createdAt: at, updatedAt: at }]));
  });
  const page = await context.newPage();
  const errors = [], cloudCalls = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('request', request => { if (request.url().includes('/rest/v1/portfolio_records')) cloudCalls.push(request.url()); });
  const base = process.env.MEMOIRE_BROWSER_BASE || 'http://127.0.0.1:5173';
  await page.goto(`${base}/app/products`);
  await page.getByRole('button', { name: 'Add Brand and link records', exact: true }).click();
  await page.getByText('Brand · active · 1 linked records · version 1', { exact: true }).waitFor();
  await page.goto(`${base}/app/leads`);
  await page.getByRole('button', { name: 'Add lead', exact: true }).click();
  const drawer = page.getByRole('dialog');
  await drawer.getByLabel('Brand / principal', { exact: true }).selectOption({ label: 'Tailin' });
  await drawer.getByLabel(/^Customer/).fill('Brand QA customer');
  await drawer.getByRole('button', { name: 'Add lead', exact: true }).click();
  await drawer.waitFor({ state: 'hidden' });
  let records = await page.evaluate(() => JSON.parse(localStorage.getItem('memoire.portfolioRecords.v1')));
  assert.equal(records.filter(row => row.kind === 'assignment').length, 2);
  const tailin = records.find(row => row.kind === 'brand' && row.name === 'Tailin');
  assert.ok(records.filter(row => row.kind === 'assignment').every(row => row.brandId === tailin.id));
  await page.getByRole('button', { name: 'Add lead', exact: true }).click();
  await drawer.getByLabel('Brand / principal', { exact: true }).selectOption('__others__');
  await drawer.getByLabel('Other brand name', { exact: true }).fill('Manual supplier');
  await drawer.getByLabel(/^Customer/).fill('Manual QA customer');
  await drawer.getByRole('button', { name: 'Add lead', exact: true }).click();
  await drawer.waitFor({ state: 'hidden' });
  records = await page.evaluate(() => JSON.parse(localStorage.getItem('memoire.portfolioRecords.v1')));
  const others = records.find(row => row.kind === 'brand' && row.name === 'Others');
  assert.ok(others);
  assert.ok(records.some(row => row.kind === 'assignment' && row.brandId === others.id && row.originalBrand === 'Manual supplier'));
  await page.goto(`${base}/app/opportunities`);
  await page.getByRole('button', { name: 'Add', exact: true }).click();
  const deal = page.getByRole('dialog');
  await deal.getByLabel(/^Account/).first().fill('Brand QA customer');
  await deal.getByLabel(/^Opportunity/).first().fill('Catalog linked opportunity');
  await deal.getByLabel('Brand / principal', { exact: true }).selectOption({ label: 'Tailin' });
  await deal.getByRole('button', { name: 'Save Opportunity', exact: true }).click();
  await page.getByRole('dialog', { name: 'Opportunity details', exact: true }).waitFor();
  records = await page.evaluate(() => JSON.parse(localStorage.getItem('memoire.portfolioRecords.v1')));
  assert.equal(records.filter(row => row.kind === 'assignment' && row.brandId === tailin.id).length, 3);
  await deal.getByLabel('Brand / principal', { exact: true }).selectOption('__others__');
  await deal.getByRole('button', { name: 'Save Opportunity', exact: true }).click();
  await deal.getByText('Enter a brand name for Others.', { exact: true }).waitFor();
  await deal.getByLabel('Other brand name', { exact: true }).fill('Manual opportunity Brand');
  await deal.getByRole('button', { name: 'Save Opportunity', exact: true }).click();
  await page.waitForFunction(() => JSON.parse(localStorage.getItem('memoire.portfolioRecords.v1')).some(row => row.kind === 'assignment' && row.originalBrand === 'Manual opportunity Brand'));
  await page.goto(`${base}/app/products`);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByTestId('portfolio-page').waitFor();
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  assert.deepEqual(errors, []); assert.deepEqual(cloudCalls, []);
  console.log('Brand browser verified: legacy registration, catalog Lead/Opportunity selection, Others manual name, ID links, demo cloud isolation, mobile.');
} finally { await browser.close(); }
