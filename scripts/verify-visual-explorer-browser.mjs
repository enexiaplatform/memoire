  await page.setViewportSize({ width: 1600, height: 1200 });
  await panel.getByRole('button', { name: 'Clear plot selection' }).click();
  await panel.getByRole('button', { name: 'Portfolio map', exact: true }).click();
  const mapBounds = await svg.boundingBox();
  await page.mouse.move(mapBounds.x + mapBounds.width * .01, mapBounds.y + mapBounds.height * .01); await page.mouse.down(); await page.mouse.move(mapBounds.x + mapBounds.width * .59, mapBounds.y + mapBounds.height * .49, { steps: 8 }); await page.mouse.up();
  await panel.getByRole('button', { name: 'Clear plot selection' }).waitFor();
